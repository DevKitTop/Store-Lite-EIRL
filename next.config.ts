import { withSentryConfig } from '@sentry/nextjs';
import type { NextConfig } from 'next';

// Derive the Supabase hostname from the env var so both dev and prod work
// without touching this file when the project ref changes.
const supabaseHostname = process.env.NEXT_PUBLIC_SUPABASE_URL
  ? new URL(process.env.NEXT_PUBLIC_SUPABASE_URL).hostname
  : '';

// CSP is now managed in middleware.ts with a per-request nonce and
// 'strict-dynamic'. Only the script-src and style-src differ from the
// baseline; the nonce-based CSP is set by middleware for HTML responses.

const nextConfig: NextConfig = {
  // Exponer explícitamente vars al build para que el Edge Runtime las tenga disponibles
  env: {
    FEATURE_SUBDOMAIN_REWRITE: process.env.FEATURE_SUBDOMAIN_REWRITE,
  },
  poweredByHeader: false,
  compress: true,
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          { key: 'X-Frame-Options', value: 'DENY' },
          {
            key: 'Permissions-Policy',
            value: 'camera=(), microphone=(), geolocation=(), payment=(self)',
          },
          {
            key: 'Strict-Transport-Security',
            value: 'max-age=31536000; includeSubDomains; preload',
          },
        ],
      },
    ];
  },
  async rewrites() {
    return [
      {
        source: '/ingest/static/:path*',
        destination: 'https://us-assets.i.posthog.com/static/:path*',
      },
      {
        source: '/ingest/:path*',
        destination: 'https://us.i.posthog.com/:path*',
      },
    ];
  },
  images: {
    remotePatterns: [
      {
        protocol: 'https',
        hostname: 'picsum.photos',
      },
      // Supabase Storage — resolved from NEXT_PUBLIC_SUPABASE_URL at build time
      ...(supabaseHostname ? [{ protocol: 'https' as const, hostname: supabaseHostname }] : []),
      {
        protocol: 'https',
        hostname: 'via.placeholder.com',
      },
      {
        protocol: 'https',
        hostname: 'www.yape.com.pe',
      },
      {
        protocol: 'https',
        hostname: 'lh3.googleusercontent.com',
      },
      {
        protocol: 'https',
        hostname: 'images.unsplash.com',
      },
    ],
  },
};

