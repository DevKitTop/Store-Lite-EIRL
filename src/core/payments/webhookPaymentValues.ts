/**
 * Maps a Culqi `charge.paid` / `charge.failed` webhook payload into a `payments`
 * insert row (W-P3.1).
 *
 * Why this exists: the webhook previously only ran an UPDATE keyed on
 * `payments.culqiChargeId`. If the webhook out-raced the charge route's insert
 * (or arrived for a payment created out-of-band), the UPDATE matched zero rows
 * and the confirmation was lost forever. The route now upserts, and this pure
 * builder decides whether the payload carries enough to construct a valid row.
 *
 * It returns `null` — meaning "update-only" — whenever a required, NOT NULL
 * column cannot be resolved: the charge id, the business/product (read back
 * from the charge `metadata` the charge route sends to Culqi), the seller
 * (the business owner, resolved by the caller), or a positive amount.
 *
 * The builder is intentionally pure: the random `trackingToken` and
 * `orderNumber` are supplied by the caller so the mapping is deterministic and
 * testable.
 */

export interface WebhookChargeData {
  id?: string;
  amount?: number;
  currency_code?: string;
  email?: string;
  reference_code?: string;
  metadata?: unknown;
}

export interface BuildWebhookPaymentValuesInput {
  /** The Culqi charge id (`chr_...`); also the upsert conflict target. */
  chargeId: string | undefined;
  data: WebhookChargeData | undefined;
  /** Resolved `businesses.owner_id`; the webhook fetches it before building. */
  sellerUserId: string | null | undefined;
  /** Pre-generated by the caller (random token, unique column). */
  trackingToken: string;
  /** Pre-generated by the caller (`resolveOrderNumber(undefined)`). */
  orderNumber: string;
}

export interface WebhookPaymentValues {
  businessId: string;
  productId: string;
  sellerUserId: string;
  amount: string;
  currency: string;
  paymentMethod: 'card';
  culqiChargeId: string;
  culqiReferenceCode: string | null;
  buyerEmail: string;
  orderNumber: string;
  trackingToken: string;
  /** Scalar quantity echoed by the charge route (`metadata.qty`, A2). */
  metadata?: { qty: number };
}

const CULQI_PLACEHOLDER_EMAIL = 'cliente@culqi.com';

function readNonEmptyString(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : null;
}

function readMetadataField(metadata: unknown, key: string): string | null {
  if (!metadata || typeof metadata !== 'object' || Array.isArray(metadata)) return null;
  return readNonEmptyString((metadata as Record<string, unknown>)[key]);
}

/**
 * Parses the scalar `qty` the charge route echoes in the Culqi charge metadata
 * (A2). Mirrors `readFulfillmentQty` from stockFulfillment (number|string →
 * integer ≥ 1) but stays local so this pure builder has no DB-schema imports.
 * Returns `null` when unusable, letting the caller omit the key entirely.
 */
function readQty(metadata: unknown): number | null {
  if (!metadata || typeof metadata !== 'object' || Array.isArray(metadata)) return null;
  const raw = (metadata as Record<string, unknown>).qty;
  const parsed = typeof raw === 'string' ? Number(raw) : raw;
  if (typeof parsed !== 'number' || !Number.isInteger(parsed) || parsed < 1) return null;
  return parsed;
}

export function buildWebhookPaymentValues(
  input: BuildWebhookPaymentValuesInput,
): WebhookPaymentValues | null {
  const { data } = input;

  const chargeId = readNonEmptyString(input.chargeId);
  if (!chargeId) return null;

  const businessId = readMetadataField(data?.metadata, 'businessId');
  if (!businessId) return null;

  const productId = readMetadataField(data?.metadata, 'productId');
  if (!productId) return null;

  const sellerUserId = readNonEmptyString(input.sellerUserId);
  if (!sellerUserId) return null;

  const amountMinor = data?.amount;
  if (typeof amountMinor !== 'number' || !Number.isFinite(amountMinor) || amountMinor <= 0) {
    return null;
  }

  // Culqi reports the amount in céntimos; `payments.amount` is decimal in soles,
  // matching the charge route (`String(amount / 100)`).
  const amount = String(amountMinor / 100);

  const currency = readNonEmptyString(data?.currency_code) ?? 'PEN';
  const buyerEmail = readNonEmptyString(data?.email) ?? CULQI_PLACEHOLDER_EMAIL;
  const culqiReferenceCode = readNonEmptyString(data?.reference_code);

  // Scalar qty (A2): only present when the charge route actually sent a
  // usable one; the key is omitted otherwise so the row stays clean.
  const qty = readQty(data?.metadata);

  return {
    businessId,
    productId,
    sellerUserId,
    amount,
    currency,
    paymentMethod: 'card',
    culqiChargeId: chargeId,
    culqiReferenceCode,
    buyerEmail,
    orderNumber: input.orderNumber,
    trackingToken: input.trackingToken,
    ...(qty !== null ? { metadata: { qty } } : {}),
  };
}
